INSERT INTO payroll_vacation_balances (employee_id, as_of_date, days)
SELECT s.employee_id, DATE '2026-09-30', s.days
  FROM vacation_balances_1c s
  JOIN employees e ON e.id = s.employee_id
   AND lower(replace(regexp_replace(btrim(e.full_name), '\s+', ' ', 'g'), 'ё', 'е')) = lower(replace(regexp_replace(btrim(s.full_name), '\s+', ' ', 'g'), 'ё', 'е'))
ON CONFLICT (employee_id, as_of_date) DO UPDATE SET days = EXCLUDED.days;

-- Не совпало ФИО — не загружено (ожидается 0 строк).
SELECT s.employee_id, s.full_name, s.days, e.full_name AS full_name_fot
  FROM vacation_balances_1c s
  LEFT JOIN employees e ON e.id = s.employee_id
 WHERE e.id IS NULL
    OR lower(replace(regexp_replace(btrim(e.full_name), '\s+', ' ', 'g'), 'ё', 'е')) <> lower(replace(regexp_replace(btrim(s.full_name), '\s+', ' ', 'g'), 'ё', 'е'))
 ORDER BY s.full_name;

