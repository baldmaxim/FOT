/**
 * Оклад по часам с ноября 2026 (решение пользователя 16.11.2026): с этого месяца оклад делится не по дням, а по часам —
 * (оклад + премиальная) × часы табеля / норма часов графика сотрудника; норма часов основы (norm_minutes) — по графику,
 * а не производственного календаря. Месяцы раньше — по дням, как были. Чистый модуль: общий для основы и правил расчёта.
 */

/** Первый месяц оклада по часам, YYYY-MM. */
export const SALARY_BY_HOURS_FROM = '2026-11';

/** Месяц (YYYY-MM или YYYY-MM-DD) считается по часам. */
export const isSalaryByHoursMonth = (month: string): boolean => month.slice(0, 7) >= SALARY_BY_HOURS_FROM;
