import { describe, expect, it, vi } from 'vitest';

vi.mock('../../config/postgres.js', () => ({
  pool: vi.fn(),
  query: vi.fn(),
  withTransaction: vi.fn(),
}));

import { addRemoteOvertime, reduceOvertime } from './payroll-basis-overtime-fix.service.js';

describe('исправление переработки в основе', () => {
  it('reduce: у дня меньшее из прежних и пересобранных минут, пустые дни уходят', () => {
    expect(reduceOvertime({ '2026-09-02': 180, '2026-09-04': 60 }, { '2026-09-02': 240 }))
      .toEqual({ '2026-09-02': 180 });
  });

  it('remote: добавляются только дни «УУ» с правкой — рабочие дни основы этого месяца без переработки', () => {
    const previous = {
      month: '2026-09-01',
      workdayDates: ['2026-09-02', '2026-09-10', '2026-09-11', '2026-09-14'],
      overtime: { '2026-09-02': 120 },
    };
    const rebuilt = {
      // Уже была переработка — прежние минуты, не пересобранные.
      '2026-09-02': 240,
      '2026-09-10': 60,
      // Пересобрано без переработки.
      '2026-09-11': 0,
      // Не «УУ» с правкой — не трогаем, хотя пересборка дала минуты.
      '2026-09-14': 60,
      // Прежде не рабочий день основы (выход) и чужой месяц — не добавляются.
      '2026-09-12': 60,
      '2026-10-01': 60,
    };
    expect(addRemoteOvertime(previous, rebuilt, ['2026-09-02', '2026-09-10', '2026-09-11', '2026-09-12', '2026-10-01']))
      .toEqual({ '2026-09-02': 120, '2026-09-10': 60 });
  });

  it('remote: добавлять нечего — прежняя переработка как есть', () => {
    const previous = { month: '2026-07-01', workdayDates: ['2026-07-06'], overtime: {} };
    // Ващук: «УУ» 10 ч при графике 10 ч — пересборка переработки не даёт.
    expect(addRemoteOvertime(previous, {}, ['2026-07-06'])).toEqual({});
  });
});
