// Признак «служебная/тестовая учётная запись» по ФИО.
//
// Правило историческое и заведомо грубое — проверка по подстроке. Настоящая фамилия
// вполне может содержать «тест», поэтому в публичном API 1С запись НЕ удаляется, а
// помечается data_quality_issue: скрывать валидный employee_id опаснее, чем показать
// сомнительный. В Excel-выгрузке поведение прежнее — строка отбрасывается.
//
// Живёт отдельным модулем, потому что нужен и Excel-сервису, и снимку руководителей:
// копия правила в двух местах разъехалась бы.

const TEST_NAME_PATTERN = /(тест|test)/i;

export const isTestPersonName = (fullName: string | null | undefined): boolean => {
  if (!fullName) return false;
  return TEST_NAME_PATTERN.test(fullName);
};
