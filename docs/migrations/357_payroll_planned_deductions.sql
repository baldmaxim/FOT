-- 357: Плановые удержания — повторяющееся удержание сотрудника на период месяцев (по образцу «Плановой доплаты»).
--
-- Запись: вид и подвид из общего справочника (payroll_deduction_kinds/_subkinds, миграции 299, 321), сумма ₽/мес,
-- «с месяца» и «по месяц» (NULL — бессрочно). В каждом месяце периода удерживается вся сумма — в расчёте ФОТ
-- плановые складываются с помесячными (staff_deductions) по виду; строки по месяцам не копируются, их
-- разворачивает один SQL (payroll-month-deductions.sql.ts): после месяца увольнения и до месяца приёма — нет.
-- Ведут кадры («Управление кадрами» → «Удержания» → «Плановые удержания») и «Зарплата» («Справочник» →
-- «Удержания» → «Плановые удержания»); окно сотрудника на «Расчётах» показывает их и историю изменений.
--
-- История (payroll_planned_deduction_changes) — для «Истории изменений» карточки: назначено, изменено, убрано с
-- месяца (период закрыт прошлым месяцем), удалено. Названия вида и подвида — снимком текстом: вид потом можно
-- удалить из справочника. planned_id без FK — удалённая запись в истории остаётся.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА (новый бэкенд читает таблицу в расчёте). Прежний бэкенд с ней работает.
-- Повторный запуск безопасен.

BEGIN;

CREATE TABLE IF NOT EXISTS payroll_planned_deductions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  kind_id     INTEGER NOT NULL REFERENCES payroll_deduction_kinds(id) ON DELETE RESTRICT,
  subkind_id  INTEGER,
  amount      NUMERIC(12,2) NOT NULL,
  month_from  DATE NOT NULL,
  month_to    DATE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT payroll_planned_deduction_amount CHECK (amount > 0),
  CONSTRAINT payroll_planned_deduction_month_from CHECK (month_from = date_trunc('month', month_from)::date),
  CONSTRAINT payroll_planned_deduction_month_to CHECK (month_to IS NULL OR month_to = date_trunc('month', month_to)::date),
  CONSTRAINT payroll_planned_deduction_period CHECK (month_to IS NULL OR month_to >= month_from)
);

-- MATCH SIMPLE: subkind_id NULL — без подвида, проверки нет; подвид чужого вида не записать (как у staff_deductions).
ALTER TABLE payroll_planned_deductions DROP CONSTRAINT IF EXISTS payroll_planned_deductions_subkind_fk;
ALTER TABLE payroll_planned_deductions ADD CONSTRAINT payroll_planned_deductions_subkind_fk
  FOREIGN KEY (kind_id, subkind_id) REFERENCES payroll_deduction_subkinds (kind_id, id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS payroll_planned_deductions_employee ON payroll_planned_deductions (employee_id);
CREATE INDEX IF NOT EXISTS payroll_planned_deductions_kind ON payroll_planned_deductions (kind_id);
CREATE INDEX IF NOT EXISTS payroll_planned_deductions_subkind ON payroll_planned_deductions (subkind_id)
  WHERE subkind_id IS NOT NULL;

COMMENT ON TABLE payroll_planned_deductions IS
  'Плановые удержания: вид, подвид, сумма ₽/мес на месяцы month_from — month_to (NULL — бессрочно), вся сумма в каждом месяце. См. миграцию 357.';

REVOKE ALL ON TABLE public.payroll_planned_deductions FROM PUBLIC;

CREATE TABLE IF NOT EXISTS payroll_planned_deduction_changes (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  planned_id        INTEGER NOT NULL,
  employee_id       INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  action            TEXT NOT NULL,
  -- «Стало»: у removed — NULL.
  kind_name         TEXT,
  subkind_name      TEXT,
  amount            NUMERIC(12,2),
  month_from        DATE,
  month_to          DATE,
  -- «Было»: у assigned — NULL.
  prev_kind_name    TEXT,
  prev_subkind_name TEXT,
  prev_amount       NUMERIC(12,2),
  prev_month_from   DATE,
  prev_month_to     DATE,
  -- Автор в колонке с NULL: ON DELETE SET NULL без DEFAULT (политика миграции 285).
  changed_by        UUID REFERENCES user_profiles(id) ON DELETE SET NULL,
  changed_at        TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT payroll_planned_deduction_change_action CHECK (action IN ('assigned', 'changed', 'closed', 'removed'))
);

CREATE INDEX IF NOT EXISTS payroll_planned_deduction_changes_employee
  ON payroll_planned_deduction_changes (employee_id, id DESC);

COMMENT ON TABLE payroll_planned_deduction_changes IS
  'История плановых удержаний для карточки: assigned / changed / closed (убрано с месяца) / removed, «было → стало» снимком. См. миграцию 357.';

REVOKE ALL ON TABLE public.payroll_planned_deduction_changes FROM PUBLIC;

COMMIT;
