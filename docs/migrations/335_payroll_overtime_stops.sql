-- 335: «Зарплата» → «Расчёты» → «Справочник» → «Без переработки».
--
-- Кому не оплачивать переработку: ни выходы в выходные сверх нормы (по заявлению), ни часы в будни сверх
-- порога (по корректировке). Список ведут вручную: сотрудник, период «с — по» (по — включительно, пусто —
-- бессрочно); возобновили оплату — ставят «по», строка остаётся историей; удаляют только ошибочную.
-- Периоды одного сотрудника не пересекаются.
--
-- Расчёт «К выплате (ФОТ)» (payroll-calc.rules.ts) снимает переработку дат внутри периода; выходы,
-- добирающие норму оклада, остаются в окладе. Основа табеля и выгрузки 1С не меняются.
--
-- Автора не храним (без FK на пользователя) — добавление, правка и удаление пишутся в аудит.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА: новый бэкенд читает таблицу в каждом расчёте «К выплате». Прежний бэкенд
-- с ней работает. Повторный запуск безопасен.

BEGIN;

-- EXCLUDE с daterange требует btree_gist (уже есть с 314; повтор — на чистой БД).
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS payroll_overtime_stops (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  date_from   DATE NOT NULL,
  date_to     DATE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT payroll_overtime_stop_dates CHECK (date_to IS NULL OR date_to >= date_from),
  CONSTRAINT payroll_overtime_stop_no_overlap
    EXCLUDE USING gist (employee_id WITH =, daterange(date_from, date_to, '[]') WITH &&)
);

COMMENT ON TABLE payroll_overtime_stops IS
  '«Без переработки» («Справочник» → «Без переработки»): кому не оплачивать переработку (выходы сверх нормы и часы по корректировкам), с — по (включительно, пусто — бессрочно); периоды сотрудника не пересекаются. См. миграцию 335.';

REVOKE ALL ON TABLE public.payroll_overtime_stops FROM PUBLIC;

COMMIT;
