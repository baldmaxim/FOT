-- 315: «Зарплата» → «Расчёты» → «Справочник»: «Доплата за проживание», разовые доплаты, «Не выплачивать».
--
-- 1. Ставка «Проживание общежития» (code = 'dormitory', миграция 313) становится «Доплатой за проживание»
--    (code = 'housing'). Её значение (на проде 630,00) — сумма по умолчанию при добавлении сотрудника в
--    таблицу «Доплата за проживание»; сама доплата сотрудника — housing_compensation условий оплаты.
--    Список проживающих в общежитии теперь открывается кнопкой «Общежитие» в шапке «Справочника».
--    Ищем по коду, не по id; значение не трогаем. Строки нет (чистая БД) — создаётся без значения.
--
-- 2. payroll_one_time_supplements — разовые доплаты: месяц, сумма, основание. За один месяц у
--    сотрудника их может быть несколько. Плановая доплата — прежний журнал payroll_planned_supplements (293).
--
-- 3. payroll_compensation_stops — «Не выплачивать»: кому не выплачивать компенсацию, период «с — по»
--    (по — включительно, пусто — бессрочно). Возобновили выплату — ставят «по», строка остаётся историей;
--    удаляют только ошибочную. Периоды одного сотрудника не пересекаются.
--
-- Автора не храним (без FK на пользователя) — добавление, правка и удаление пишутся в аудит.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА. Прежний бэкенд с ней работает (у ставки просто пропадёт кнопка
-- общежития). Повторный запуск безопасен.

BEGIN;

UPDATE payroll_rates
   SET name = 'Доплата за проживание', code = 'housing', updated_at = now()
 WHERE code = 'dormitory'
   AND NOT EXISTS (SELECT 1 FROM payroll_rates WHERE code = 'housing');

INSERT INTO payroll_rates (name, code)
SELECT 'Доплата за проживание', 'housing'
 WHERE NOT EXISTS (SELECT 1 FROM payroll_rates WHERE code = 'housing');

COMMENT ON COLUMN payroll_rates.code IS
  'Машинный код ставки, к которой привязан функционал (housing — «Доплата за проживание»: сумма по умолчанию в одноимённой таблице); такую ставку не удалить и не переименовать.';

CREATE TABLE IF NOT EXISTS payroll_one_time_supplements (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  month       DATE NOT NULL,
  amount      NUMERIC(12,2) NOT NULL,
  reason      TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT payroll_one_time_supplement_month CHECK (month = date_trunc('month', month)::date),
  CONSTRAINT payroll_one_time_supplement_amount CHECK (amount > 0),
  CONSTRAINT payroll_one_time_supplement_reason CHECK (btrim(reason) <> '' AND length(reason) <= 200)
);

CREATE INDEX IF NOT EXISTS payroll_one_time_supplements_employee_month
  ON payroll_one_time_supplements (employee_id, month);

COMMENT ON TABLE payroll_one_time_supplements IS
  'Разовые доплаты («Справочник» → «Доплата»): месяц (первое число), сумма, основание; за месяц — сколько угодно. См. миграцию 315.';

REVOKE ALL ON TABLE public.payroll_one_time_supplements FROM PUBLIC;

-- EXCLUDE с daterange требует btree_gist (уже есть с 314; повтор — на чистой БД без 314).
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS payroll_compensation_stops (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  date_from   DATE NOT NULL,
  date_to     DATE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT payroll_compensation_stop_dates CHECK (date_to IS NULL OR date_to >= date_from),
  CONSTRAINT payroll_compensation_stop_no_overlap
    EXCLUDE USING gist (employee_id WITH =, daterange(date_from, date_to, '[]') WITH &&)
);

COMMENT ON TABLE payroll_compensation_stops IS
  '«Не выплачивать» («Справочник» → «Не выплачивать»): кому не выплачивать компенсацию, с — по (включительно, пусто — бессрочно); периоды сотрудника не пересекаются. См. миграцию 315.';

REVOKE ALL ON TABLE public.payroll_compensation_stops FROM PUBLIC;

COMMIT;
