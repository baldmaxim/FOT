-- 368: Зарплата — норма графика по дням в основе расчёта (для расшифровки оклада по часам в листке).
--
-- Зачем. С ноября 2026 оклад делится на норму часов графика (norm_minutes основы, миграция 331). Основа хранит итог
-- нормы, но не то, из каких дней он сложен. Графики меняют задним числом и правят шаблоны на месте, поэтому раскладку
-- закрытого месяца по нынешним графикам восстанавливать нельзя: итог мог совпасть, а рабочие даты — нет.
--
-- norm_plan — {"days": {"YYYY-MM-DD": минуты нормы дня}, "saturdays": n, "sundays": n, "quota_minutes": m}: норма
-- каждой даты по графику (дни с нормой 0 не пишутся) и квота обязательных Сб/Вс с минутами её дня — из тех же графиков
-- и в тот же момент, что norm_minutes (schedule-month-norm.ts). Только месяцы оклада по часам (с 2026-11). В расчёт
-- и в basis_hash не входит — только поясняет norm_minutes в листке карточки «Зарплата».
-- NULL — месяц по дням, графика нет хоть на день или основа снята до 368 (тогда в листке — только итог нормы).
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА: новый бэкенд пишет и читает колонку. Старый бэкенд её не замечает.
-- Повторный запуск безопасен.

BEGIN;

ALTER TABLE timesheet_version_payroll_basis ADD COLUMN IF NOT EXISTS norm_plan JSONB;

COMMENT ON COLUMN timesheet_version_payroll_basis.norm_plan IS
  'Норма графика по дням на момент снятия основы: {"days": {"YYYY-MM-DD": минуты}, "saturdays", "sundays", '
  '"quota_minutes"}. Только месяцы оклада по часам (с 2026-11); в расчёт и хэш не входит. NULL — основа до 368, '
  'месяц по дням или нет графика.';

COMMIT;
