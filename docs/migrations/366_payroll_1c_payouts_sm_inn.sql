-- 366: «Перечислено (1С)» — ведомости выплаты АО «Служба механизации» (СМ, ИНН 7705794997) рядом с СУ-10.
--
-- Зачем. Сотрудникам СМ 1С перечисляет аванс, зарплату, увольнения и премии ведомостями своей организации. CHECK
-- миграции 328 пускал только ИНН СУ-10, и выплаты СМ за сентябрь 2026 (8 файлов XML ЗУП) загрузить было нельзя.
-- Экраны читают выплаты по сотруднику без организации: у совместителя суммы СУ-10 и СМ складываются.
--
-- Грузит их только генератор scripts/build-payouts-xml-sql.ts. Кнопка «Загрузить из 1С» и реестр ФСС по-прежнему
-- принимают только СУ-10 (константа PAYOUTS_1C_ORGANIZATION_INN).
--
-- content_hash организацию не включает и не пересчитывается: документы СУ-10 остаются как были.
--
-- ПРИМЕНЯТЬ ДО ЗАГРУЗКИ SQL СМ. Бэкенду не нужна, прежний работает. Повторный запуск безопасен.

BEGIN;

ALTER TABLE payroll_1c_payout_documents DROP CONSTRAINT IF EXISTS payroll_1c_payout_documents_organization_inn_check;
ALTER TABLE payroll_1c_payout_documents ADD CONSTRAINT payroll_1c_payout_documents_organization_inn_check
  CHECK (organization_inn IN ('7736255508', '7705794997'));

COMMENT ON COLUMN payroll_1c_payout_documents.organization_inn IS
  'ИНН организации ведомости: 7736255508 — ООО «СУ-10», 7705794997 — АО «Служба механизации» (366).';
COMMENT ON COLUMN payroll_1c_payout_documents.content_hash IS
  'sha256 канонического содержимого исходного документа 1С: ГУИД, номер ЗУП3, дата, месяц (ПериодРегистрации 1С), '
  'способ, итог, ключи строк. Поля формата (номер ЗУП2, организация, бригада, зарплатный проект, id_all) не входят. '
  'Ведомость, которую 1С провела другим месяцем, генератор по решению пользователя может положить в другой '
  'period_month — тогда месяц в хеше исходный, а решение записано в resolution_reason строк и manifest загрузки (366).';

COMMIT;
