-- 348: карточка «Зарплаты» → блок «Пересчёт»: сколько доплатить после правки оклада задним числом.
--
-- Расчёт ФОТ не хранится: прошлый месяц считается заново по текущей истории условий, а назначение условий обрезает и
-- удаляет прежние строки (assignTerms). Поэтому прежние условия сохраняются в момент правки: «Было» считается
-- по ним и тем же дням табеля, что и «Стало», — в разницу попадают только оклад, ставка и премиальная часть.
--
-- previous_terms — вся история условий сотрудника до правки (суммы текстом, даты YYYY-MM-DD).
-- paid_months_1c — первые числа месяцев, за которые на момент правки в 1С была статья «По трудовому договору»:
-- дат у этих сумм нет, а повторная загрузка сдвинула бы updated_at, поэтому список фиксируется.
-- settled_at — нажали «Доплачено»: запись больше не считается, блок исчезает; строка остаётся историей.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА: новый бэкенд пишет в таблицу при сохранении условий задним числом и читает её в карточке.
-- Прежний бэкенд с ней работает. Повторный запуск безопасен.

BEGIN;

CREATE TABLE IF NOT EXISTS payroll_terms_recalcs (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id    INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  effective_from DATE NOT NULL,
  previous_terms JSONB NOT NULL,
  paid_months_1c DATE[] NOT NULL DEFAULT '{}',
  created_by     UUID REFERENCES user_profiles(id) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  settled_by     UUID REFERENCES user_profiles(id) ON DELETE SET NULL,
  settled_at     TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS payroll_terms_recalcs_open_idx
  ON payroll_terms_recalcs (employee_id)
  WHERE settled_at IS NULL;

COMMENT ON TABLE payroll_terms_recalcs IS
  'Блок «Пересчёт» карточки «Зарплаты»: прежние условия на момент правки оклада задним числом; settled_at — доплачено. См. миграцию 348.';

REVOKE ALL ON TABLE public.payroll_terms_recalcs FROM PUBLIC;

COMMIT;
