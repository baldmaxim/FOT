-- 376: файлы шаблонов графиков работы («Графики работы» → «Шаблоны графиков»): приказ, график сменности.
--
-- Строка — файл в R2 (r2_key). Графики не удаляются, а уходят в архив (302): файлы архивного графика
-- остаются. Если строка графика всё же удалена — файлы уходят каскадом, объекты R2 остаются сиротами.
-- Видят файлы те же, кто видит шаблоны графиков; прикрепляют и удаляют — кто их правит.
-- В общую таблицу documents не кладём: там файл увидел бы сотрудник в «Моих документах».
--
-- Автора не храним (как у файлов доплат в 354): прикрепление и удаление пишутся в аудит
-- (WORK_SCHEDULE_FILE_UPLOADED / _DELETED) в той же транзакции, что и строка файла.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА: список графиков считает files_count по этой таблице.
-- Прежний бэкенд таблицу не читает. Повторный запуск безопасен. Откат — docs/rollbacks/376_*.

BEGIN;

CREATE TABLE IF NOT EXISTS work_schedule_files (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_id UUID NOT NULL REFERENCES work_schedules(id) ON DELETE CASCADE,
  r2_key      TEXT NOT NULL UNIQUE,
  file_name   TEXT NOT NULL,
  file_size   INTEGER NOT NULL,
  mime_type   TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT work_schedule_file_r2_key CHECK (btrim(r2_key) <> ''),
  CONSTRAINT work_schedule_file_name CHECK (btrim(file_name) <> '' AND length(file_name) <= 200),
  CONSTRAINT work_schedule_file_size CHECK (file_size > 0 AND file_size <= 25 * 1024 * 1024),
  CONSTRAINT work_schedule_file_mime CHECK (btrim(mime_type) <> '')
);

CREATE INDEX IF NOT EXISTS work_schedule_files_schedule
  ON work_schedule_files (schedule_id, created_at, id);

COMMENT ON TABLE work_schedule_files IS
  'Файлы шаблонов графиков (R2): не больше 20 у графика, до 25 МБ, PDF/JPG/PNG/WEBP/DOC/DOCX/XLS/XLSX. См. миграцию 376.';

REVOKE ALL ON TABLE public.work_schedule_files FROM PUBLIC;

COMMIT;
