-- Раздел «Зарплата»: в список payroll_section_access (миграция 310) добавлены две учётки —
-- Бадонова Светлана Малановна и Бутенко Наталья Валентиновна (обе — роль «Администратор»).
-- 15.10 при переходе на список они раздел потеряли, теперь возвращаются.
--
-- Меняется только список: две строки, отбор строго по двум UUID учёток (user_profiles.id).
-- Остальные пять учёток списка, роли и данные «Зарплаты» не трогаются.
-- Охват — как у других админов из списка: весь штат с правкой, включая себя
-- (запрет правки себя в payroll-scope.service действует только для не-админов).
--
-- Отсутствующие id (локальная/тестовая БД) пропускаются. Повторный запуск безопасен.
-- Действует со следующего запроса к API; пункт меню — после перезахода.
--
-- Убрать: DELETE FROM public.payroll_section_access
--          WHERE user_id IN ('32c843c1-f735-48ba-a744-7b6670c8ee78', '068364fa-05d7-433c-bec1-ff1152287d1c');
--
-- Код не меняется: бэкенд и фронтенд не деплоить, только миграция.

BEGIN;

INSERT INTO public.payroll_section_access (user_id)
SELECT id
  FROM public.user_profiles
 WHERE id IN (
   '32c843c1-f735-48ba-a744-7b6670c8ee78',  -- Бадонова Светлана Малановна
   '068364fa-05d7-433c-bec1-ff1152287d1c'   -- Бутенко Наталья Валентиновна
 )
ON CONFLICT (user_id) DO NOTHING;

COMMIT;
