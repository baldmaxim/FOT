-- 321: Удержания — подвиды видов («Спецодежда» → «Каска», «Штрафы» → «Курение») и одна запись удержания
-- на кадры и «Зарплату».
--
-- Подвиды. У любого вида справочника (payroll_deduction_kinds, миграция 299) — свои подвиды со своей суммой
-- по умолчанию: «+» у вида в «Управление кадрами» → «Удержания» → «Виды удержаний» и в «Зарплата» →
-- «Справочник» → «Удержания». Справочник подвидов общий, как и видов. Подвид удержания необязателен;
-- составной FK (kind_id, subkind_id) не даёт записать подвид чужого вида. Удаление неиспользуемого вида
-- уносит его подвиды (CASCADE); подвид, назначенный сотрудникам, не удалить (RESTRICT).
--
-- Одна запись. Удержание сотрудника — строка staff_deductions (вид, подвид, месяц, сумма): её ведут кадры
-- и «Зарплата» («Справочник» → «Удержания» → «Сотрудники»), окно сотрудника на «Расчётах» её только
-- показывает. Прежняя модель «Зарплаты» — галочки видов (payroll_employee_deductions, миграция 300) и
-- «Сумма, ₽/мес» в условиях оплаты (payroll_compensation_terms.deduction_amount) — с этой миграции не
-- читается и не пишется (удалить отдельной миграцией). На момент миграции на проде там пусто — переносить
-- нечего; если данные появились — миграция останавливается, чтобы их не потерять.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА. Прежний бэкенд с ней работает. Повторный запуск безопасен.
-- Перед рестартом нового бэкенда повторить проверку ниже (прежний ещё мог записать по-старому).

BEGIN;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM payroll_employee_deductions) THEN
    RAISE EXCEPTION 'Есть виды удержаний у сотрудников (payroll_employee_deductions) — перенесите их в удержания до миграции 321';
  END IF;
  IF EXISTS (SELECT 1 FROM payroll_compensation_terms WHERE deduction_amount > 0) THEN
    RAISE EXCEPTION 'Есть сумма удержания в условиях оплаты (deduction_amount > 0) — перенесите её в удержания до миграции 321';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS payroll_deduction_subkinds (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind_id        INTEGER NOT NULL REFERENCES payroll_deduction_kinds(id) ON DELETE CASCADE,
  name           TEXT NOT NULL,
  default_amount NUMERIC(12,2),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT payroll_deduction_subkind_name CHECK (btrim(name) <> '' AND length(name) <= 100),
  CONSTRAINT payroll_deduction_subkind_default_amount CHECK (default_amount IS NULL OR default_amount > 0)
);

-- Без учёта регистра и пробелов по краям, в пределах вида: «Каска» у «Спецодежды» одна, у «ТМЦ» — своя.
CREATE UNIQUE INDEX IF NOT EXISTS payroll_deduction_subkinds_name_uniq
  ON payroll_deduction_subkinds (kind_id, lower(btrim(name)));
-- Под составной FK из staff_deductions: подвид — вместе со своим видом.
CREATE UNIQUE INDEX IF NOT EXISTS payroll_deduction_subkinds_kind_id_uniq
  ON payroll_deduction_subkinds (kind_id, id);

COMMENT ON TABLE payroll_deduction_subkinds IS
  'Подвиды видов удержаний (общие для кадров и «Зарплаты»): название, сумма по умолчанию. См. миграцию 321.';
COMMENT ON COLUMN payroll_deduction_subkinds.default_amount IS
  'Сумма по умолчанию для удержания с этим подвидом (вместо суммы вида); NULL — берётся сумма вида.';

ALTER TABLE staff_deductions ADD COLUMN IF NOT EXISTS subkind_id INTEGER;
ALTER TABLE staff_deductions DROP CONSTRAINT IF EXISTS staff_deductions_subkind_fk;
-- MATCH SIMPLE: subkind_id NULL — удержание без подвида, проверки нет.
ALTER TABLE staff_deductions ADD CONSTRAINT staff_deductions_subkind_fk
  FOREIGN KEY (kind_id, subkind_id) REFERENCES payroll_deduction_subkinds (kind_id, id) ON DELETE RESTRICT;

-- Проверка RESTRICT при удалении подвида и подсчёт «назначен сотрудникам».
CREATE INDEX IF NOT EXISTS staff_deductions_subkind
  ON staff_deductions (kind_id, subkind_id) WHERE subkind_id IS NOT NULL;

COMMENT ON COLUMN staff_deductions.subkind_id IS
  'Подвид из payroll_deduction_subkinds того же вида; NULL — без подвида. См. миграцию 321.';
COMMENT ON TABLE staff_deductions IS
  'Удержания сотрудников: вид, подвид, месяц удержания (1-е число), сумма. Ведут кадры («Управление кадрами» → «Удержания») и «Зарплата» («Справочник» → «Удержания»). См. миграции 318, 321.';
COMMENT ON TABLE payroll_employee_deductions IS
  'Не используется с миграции 321: удержания — staff_deductions. Удалить отдельной миграцией.';
COMMENT ON COLUMN payroll_compensation_terms.deduction_amount IS
  'Не используется с миграции 321: удержания — staff_deductions. Удалить отдельной миграцией.';

REVOKE ALL ON TABLE public.payroll_deduction_subkinds FROM PUBLIC;

COMMIT;
