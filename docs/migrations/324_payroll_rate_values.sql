-- 324: «Зарплата» → «Справочник» → «Ставки»: значения ставок по месяцам и ставка «Проезд».
--
-- Зачем. Ставки меняются, а прошлые месяцы должны показывать значение своего периода. До 324 у ставки было
-- одно значение (payroll_rates.amount): смена «Доплаты за общежитие» переписывала все прошлые месяцы.
-- Теперь значения — в payroll_rate_values: «с какого месяца» (1-е число) и сумма. Значение за месяц M —
-- последняя запись с effective_from <= M (функция payroll_rate_value). Первое значение действует
-- «с начала» (2000-01-01), следующие сервер пишет только с текущего месяца МСК и позже. NULL в истории —
-- ставку отключили с этого месяца.
--
-- «Проезд» (code = 'travel') — сумма за месяц всем, кроме рабочих и тех, у кого в месяце есть день
-- «Без проезда» (payroll_compensation_stops). Создаётся без значения — вносят в «Ставках».
--
-- payroll_rates.amount остаётся копией значения на текущий месяц: её читает прежний бэкенд (откат).
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА, одним заходом с ним; в это окно ставки не править. Повторный запуск
-- безопасен и досинхронизирует правки, сделанные прежним бэкендом (см. шаг 4).

BEGIN;

-- 1. Ставка «Проезд»: строка с таким названием без кода (завели руками) получает код, иначе создаётся
--    без значения.
UPDATE payroll_rates
   SET code = 'travel', updated_at = now()
 WHERE lower(btrim(name)) = 'проезд'
   AND code IS NULL
   AND NOT EXISTS (SELECT 1 FROM payroll_rates WHERE code = 'travel');

INSERT INTO payroll_rates (name, code)
SELECT 'Проезд', 'travel'
 WHERE NOT EXISTS (SELECT 1 FROM payroll_rates WHERE code = 'travel');

-- 2. Значения ставок по месяцам. Автора не храним (без FK на пользователя) — правка пишется в аудит.
CREATE TABLE IF NOT EXISTS payroll_rate_values (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rate_id        INTEGER NOT NULL REFERENCES payroll_rates(id) ON DELETE CASCADE,
  effective_from DATE NOT NULL,
  amount         NUMERIC(12,2),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT payroll_rate_value_month_start CHECK (effective_from = date_trunc('month', effective_from)::date),
  CONSTRAINT payroll_rate_value_amount CHECK (amount IS NULL OR amount >= 0),
  CONSTRAINT payroll_rate_values_uniq UNIQUE (rate_id, effective_from)
);

REVOKE ALL ON TABLE public.payroll_rate_values FROM PUBLIC;

-- 3. Перенос: заданное значение ставки без истории действует «с начала» — прошлые месяцы видят то же,
--    что и до 324. Ставка без значения истории не получает.
INSERT INTO payroll_rate_values (rate_id, effective_from, amount)
SELECT r.id, DATE '2000-01-01', r.amount
  FROM payroll_rates r
 WHERE r.amount IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM payroll_rate_values v WHERE v.rate_id = r.id);

-- 4. Досинхронизация (повторный запуск): прежний бэкенд меняет только payroll_rates.amount. Колонка новее
--    истории и расходится со значением на текущий месяц — значение с текущего месяца МСК берётся из неё.
--    Новый бэкенд пишет колонку и историю одной транзакцией (одно now()) — его правки сюда не попадают.
WITH today AS (SELECT (now() AT TIME ZONE 'Europe/Moscow')::date AS day),
state AS (
  SELECT r.id, r.amount, r.updated_at,
         (SELECT v.amount FROM payroll_rate_values v
           WHERE v.rate_id = r.id AND v.effective_from <= today.day
           ORDER BY v.effective_from DESC LIMIT 1) AS value_now,
         (SELECT max(v.updated_at) FROM payroll_rate_values v WHERE v.rate_id = r.id) AS values_updated_at
    FROM payroll_rates r, today
)
INSERT INTO payroll_rate_values (rate_id, effective_from, amount)
SELECT s.id, date_trunc('month', today.day)::date, s.amount
  FROM state s, today
 WHERE s.values_updated_at IS NOT NULL
   AND s.updated_at > s.values_updated_at
   AND s.amount IS DISTINCT FROM s.value_now
ON CONFLICT (rate_id, effective_from) DO UPDATE SET amount = EXCLUDED.amount, updated_at = now();

-- 5. Значение ставки по коду на день (берётся месяц дня). Нет ставки или истории — NULL.
CREATE OR REPLACE FUNCTION public.payroll_rate_value(p_code text, p_day date)
RETURNS numeric
LANGUAGE sql
STABLE
AS $$
  SELECT v.amount
    FROM payroll_rate_values v
    JOIN payroll_rates r ON r.id = v.rate_id
   WHERE r.code = p_code
     AND v.effective_from <= p_day
   ORDER BY v.effective_from DESC
   LIMIT 1
$$;

COMMENT ON TABLE payroll_rate_values IS
  'Значения ставок «Справочника» по месяцам: с effective_from (1-е число) и до следующей записи; NULL — ставку отключили. Первое значение — с 2000-01-01 («с начала»).';
COMMENT ON FUNCTION public.payroll_rate_value(text, date) IS
  'Значение ставки payroll_rates.code на месяц дня p_day: последняя запись payroll_rate_values с effective_from <= p_day.';
COMMENT ON COLUMN payroll_rates.amount IS
  'Копия значения на текущий месяц для прежнего бэкенда (откат). Значения по месяцам — payroll_rate_values.';
COMMENT ON COLUMN payroll_rates.code IS
  'Машинный код ставки, к которой привязан функционал (housing — «Доплата за проживание»: сумма по умолчанию в одноимённой таблице; dormitory_allowance — «Доплата за общежитие»: сумма всем из одноимённой таблицы; travel — «Проезд»: сумма за месяц всем, кроме рабочих и «Без проезда»); такую ставку не удалить и не переименовать.';
COMMENT ON COLUMN payroll_compensation_terms.travel_compensation IS
  'Не используется с 324: проезд — ставка travel «Справочника».';

COMMIT;
