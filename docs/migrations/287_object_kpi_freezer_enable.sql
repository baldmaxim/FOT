-- 287: автофиксация плана KPI объектов на 3-й рабочий день (п. 2.8 приказа о KPI закрытия КС-2).
-- Применять ПОСЛЕ деплоя бэкенда 9d8b0965 — можно сразу после него. До деплоя не применять:
-- старый бэкенд зафиксировал бы текущий месяц с замороженными суммами, и до выкладки нового
-- его цифры перестали бы обновляться при правках.
--
-- Ждать исправления данных объектов не нужно. Фиксация закрепляет только плановую ЗОС,
-- контрольную дату и число месяцев (п. 6.3); остаток и план зафиксированного месяца считаются
-- по текущим данным, а правка исходных данных такого месяца требует основания и попадает в историю.
-- Включённая джоба в течение часа фиксирует ТЕКУЩИЙ месяц у всех объектов без снимка;
-- прошлые месяцы она не трогает.
-- Идемпотентно.

INSERT INTO system_settings (key, value, description, is_secret)
VALUES
  ('object_kpi_freezer_enabled', 'true',
   'KPI объектов: автоматическая фиксация плана месяца (kill switch).', false),
  ('object_kpi_fix_working_day', '3',
   'KPI объектов: рабочий день месяца, с которого план фиксируется автоматически (п. 2.8 приказа).', false)
ON CONFLICT (key) DO UPDATE
  SET value = EXCLUDED.value;
