-- 344: Зарплата — минуты к оплате по дням в основе расчёта, для почасовой ставки.
--
-- Зачем. Основа (timesheet_version_payroll_basis, миграция 331) хранит даты рабочих дней и выходов, но не часы:
-- оклад считается днями. Почасовому сотруднику нужны часы дня, снятые вместе с датами при закрытии табеля:
-- графики меняют задним числом, поэтому при чтении их считать нельзя.
--
-- paid_minutes — {"YYYY-MM-DD": минуты}: целые часы дня × 60 по правилам classifyBasisDays. У окладника поле в расчёте
-- не участвует, но заполняется у всех: почасовую ставку могут назначить задним числом.
-- NULL — основа снята до 344; дозаполняет scripts/backfill-payroll-basis-paid-minutes.ts новой revision.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА: новый бэкенд читает колонку в расчёте. Старый бэкенд её не замечает.
-- Повторный запуск безопасен.

BEGIN;

ALTER TABLE timesheet_version_payroll_basis ADD COLUMN IF NOT EXISTS paid_minutes JSONB;

COMMENT ON COLUMN timesheet_version_payroll_basis.paid_minutes IS
  'Минуты к оплате по дням при почасовой ставке: {"YYYY-MM-DD": минуты}. Часы дня как в «Едином 1С», не больше смены '
  'по графику; правка часов — как есть. Нет даты — часы определить нельзя (нет графика и правки), расчёт неполный. '
  'NULL — основа до миграции 344.';

COMMIT;
