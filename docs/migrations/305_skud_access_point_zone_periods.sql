-- 305: СКУД — тип зоны точки доступа («внутренняя» / «внешняя») с датой начала действия.
--
-- Зачем. У точки был один флаг без дат (skud_access_point_settings.is_internal), и любой расчёт
-- за любую дату брал текущее значение. 12.10.2026 «кпп ASTERUS» переключили с внутренней на
-- внешнюю — проходы через неё стали учитываться за все прошлые месяцы, часы в табелях (в том
-- числе закрытых) изменились у 340 человек.
--
-- Теперь у точки история: строка = «с такого-то рабочего дня точка внутренняя/внешняя». Тип
-- определяется по РАБОЧЕЙ ДАТЕ смены (p_date), а не по дате отдельного прохода: проход 01.10,
-- закрывающий ночную смену 30.09, считается по правилу 30.09. Точки без истории — внешние.
--
-- Что делает миграция:
--   1. таблица истории skud_access_point_zone_periods и перенос в неё текущих внутренних точек
--      («с самого начала», 2000-01-01);
--   2. «кпп ASTERUS»: внутренняя по 30.09.2026, внешняя с 01.10.2026;
--   3. очередь пересборки сводки и «Дороги» после смены типа (skud_access_point_zone_reconcile);
--   4. функция is_access_point_internal(имя, рабочая дата);
--   5. recalculate_skud_daily_summary (тело из 168) и is_skud_anomalous_day (тело из 161) читают
--      тип зоны через неё — остальной текст функций не менялся.
--
-- История — источник только для расчёта часов в табеле (сводка, пары, «Дорога», аномальность
-- дня). Экраны портала — присутствие, списки проходов, выгрузки СКУД — работают прежним кодом и
-- берут тип «на сегодня» из skud_access_point_settings. Эта таблица остаётся и меняется вместе
-- с историей: смена типа в окне «Точки доступа» пишет в обе в одной транзакции.
--
-- Сохранённые строки skud_daily_summary миграция не трогает. Пересборку того, что успело
-- пересчитаться с неверным типом, делает scripts/reconcile-access-point-zone.ts после деплоя.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА (и сразу деплоить бэкенд: в промежутке тип зоны не менять —
-- прежний бэкенд пишет только в skud_access_point_settings, без истории). Повторный запуск безопасен.

BEGIN;

