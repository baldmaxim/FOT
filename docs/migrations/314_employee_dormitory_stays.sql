-- 314: «Общежитие» — кто из сотрудников живёт в общежитии («Управление кадрами» → «Общежитие»).
--
-- Строка — одно проживание: сотрудник, дата въезда, дата выезда (пусто — живёт), адрес или номер.
-- Повторный въезд — новая строка. Периоды одного сотрудника не пересекаются; день выезда может быть
-- днём следующего въезда (переселение) — поэтому диапазон [въезд, выезд), а выезд строго позже въезда:
-- иначе одинаковые даты дали бы пустой период, который ни с чем не пересекается.
-- Ведут в «Управлении кадрами» (право /staff-control/dormitory), только чтение — в «Зарплате»
-- («Справочник» → «Ставки» → «Проживание общежития», миграция 313).
--
-- Автора не храним (без FK на пользователя) — добавление, правка и удаление пишутся в аудит.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА. Прежний бэкенд с ней работает. Повторный запуск безопасен.

BEGIN;

-- EXCLUDE с daterange требует btree_gist для оператора = по scalar-колонкам.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS employee_dormitory_stays (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  check_in    DATE NOT NULL,
  check_out   DATE,
  address     TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT employee_dormitory_stay_dates CHECK (check_out IS NULL OR check_out > check_in),
  CONSTRAINT employee_dormitory_stay_address CHECK (btrim(address) <> '' AND length(address) <= 200),
  CONSTRAINT employee_dormitory_stay_no_overlap
    EXCLUDE USING gist (employee_id WITH =, daterange(check_in, check_out, '[)') WITH &&)
);

COMMENT ON TABLE employee_dormitory_stays IS
  'Проживание сотрудников в общежитии («Управление кадрами» → «Общежитие»): въезд, выезд, адрес; периоды одного сотрудника не пересекаются. См. миграцию 314.';

REVOKE ALL ON TABLE public.employee_dormitory_stays FROM PUBLIC;

-- Право «Управление кадрами — Общежитие» (образец — 291).
INSERT INTO access_pages (
  key, label, group_code, group_label, area, surface,
  supports_edit, requires_data_scope, requires_employee_variant,
  sort_order, is_active, is_system
)
VALUES
  ('/staff-control/dormitory', 'Управление кадрами — Общежитие', 'work', 'Управление',
   'admin', 'technical', true, false, false, 109, true, true)
ON CONFLICT (key) DO UPDATE SET
  label         = EXCLUDED.label,
  group_code    = EXCLUDED.group_code,
  group_label   = EXCLUDED.group_label,
  area          = EXCLUDED.area,
  surface       = EXCLUDED.surface,
  supports_edit = EXCLUDED.supports_edit,
  sort_order    = EXCLUDED.sort_order,
  is_active     = EXCLUDED.is_active;

-- Сразу — администратор и кадровый админ; остальным — галочкой в «Ролях».
INSERT INTO role_page_access (role_code, page_path, can_view, can_edit)
VALUES
