-- 317: «Зарплата» → «Расчёты» → «Справочник» → «Ставки»: «Доплата за общежитие».
--
-- Кому платят за то, что он НЕ живёт в общежитии компании. Список ведут вручную: сотрудник, период
-- «с — по» (по — включительно, пусто — бессрочно); прекратили — ставят «по», строка остаётся историей;
-- удаляют только ошибочную. Периоды одного сотрудника не пересекаются.
--
-- Сумма одна на всех — значение ставки code = 'dormitory_allowance' (вносят в «Ставках»); у строк её нет.
--
-- Сервер (не БД) стережёт правила записи: в дни проживания в общежитии (employee_dormitory_stays,
-- миграция 314) доплату не назначить; у сотрудника одна доплата из двух — «за проживание»
-- (housing_compensation условий оплаты) или «за общежитие».
--
-- Автора не храним (без FK на пользователя) — добавление, правка и удаление пишутся в аудит.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА. Прежний бэкенд с ней работает (новая ставка видна в «Ставках»,
-- правится только её значение). Повторный запуск безопасен.

BEGIN;

-- Ставка ищется по коду. Строка с таким названием без кода (завели руками до 317) получает код,
-- иначе создаётся без значения. Значение не трогаем.
UPDATE payroll_rates
   SET code = 'dormitory_allowance', updated_at = now()
 WHERE lower(btrim(name)) = 'доплата за общежитие'
   AND code IS NULL
   AND NOT EXISTS (SELECT 1 FROM payroll_rates WHERE code = 'dormitory_allowance');

INSERT INTO payroll_rates (name, code)
SELECT 'Доплата за общежитие', 'dormitory_allowance'
 WHERE NOT EXISTS (SELECT 1 FROM payroll_rates WHERE code = 'dormitory_allowance');

COMMENT ON COLUMN payroll_rates.code IS
  'Машинный код ставки, к которой привязан функционал (housing — «Доплата за проживание»: сумма по умолчанию в одноимённой таблице; dormitory_allowance — «Доплата за общежитие»: сумма всем из одноимённой таблицы); такую ставку не удалить и не переименовать.';

-- EXCLUDE с daterange требует btree_gist (уже есть с 314; повтор — на чистой БД).
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS payroll_dormitory_allowances (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  date_from   DATE NOT NULL,
  date_to     DATE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT payroll_dormitory_allowance_dates CHECK (date_to IS NULL OR date_to >= date_from),
  CONSTRAINT payroll_dormitory_allowance_no_overlap
    EXCLUDE USING gist (employee_id WITH =, daterange(date_from, date_to, '[]') WITH &&)
);

COMMENT ON TABLE payroll_dormitory_allowances IS
  '«Доплата за общежитие» («Справочник» → «Ставки»): кому платят за то, что не живёт в общежитии компании; с — по (включительно, пусто — бессрочно); периоды сотрудника не пересекаются; сумма — ставка dormitory_allowance. См. миграцию 317.';

REVOKE ALL ON TABLE public.payroll_dormitory_allowances FROM PUBLIC;

COMMIT;
