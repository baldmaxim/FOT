-- 266: разделение «отдел виден» и «в отдел можно назначать».
-- Применять ДО деплоя бэкенда.
--
-- Отдел, выпавший из фильтра синхронизации или удалённый в Sigur, нельзя просто
-- гасить: в нём могут числиться сотрудники, а погашенный узел ломает дерево
-- (/api/structure), сводку подачи табеля, строку начальника участка и скоуп
-- табельщицы. Такой отдел остаётся is_active = true (виден и доступен для
-- просмотра/фильтрации), но получает is_assignable = false — назначать,
-- переводить и восстанавливать в него сотрудников нельзя.
--
-- DEFAULT true нужен только чтобы миграция не ломала существующие строки;
-- корректное состояние проставляет разовый бэкфилл
-- (fot-server/scripts/backfill-department-assignable.ts) и дальнейшие синки.

BEGIN;

ALTER TABLE public.org_departments
  ADD COLUMN IF NOT EXISTS is_assignable boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN public.org_departments.is_assignable IS
  'Можно ли назначать сюда сотрудников. false — отдел вне разрешённого поддерева синхронизации Sigur или удалён в Sigur, но виден ради уже числящихся людей.';

COMMIT;
