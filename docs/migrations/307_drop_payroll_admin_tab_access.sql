-- 307: Раздел «Зарплата» — удаление вкладки «Администрирование» и её ключа /salary/admin (миграция 294).
--
-- Зачем. Вкладка была заглушкой «Подключение по API к 1С и другим системам». Доступы и ключи
-- для 1С будут в разделе «Система», поэтому вкладка, её ключ в каталоге прав и грант роли admin
-- убраны из кода и из БД (повтор паттерна 104 / 290).
--
-- Что удаляется: строка каталога access_pages и гранты ролей на /salary/admin.
-- НЕ трогается: остальные ключи раздела (/salary/payments, /salary/terms, …), персональные гранты
-- payroll_access_grants (они про весь раздел, список ключей — PAYROLL_GRANT_PAGES), данные зарплаты.
-- Доступ к разделу ни у кого не пропадает: /salary/admin был выдан только роли admin, у неё есть
-- и остальные ключи раздела.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА (вместе с 306). Новый бэкенд тогда стартует, когда ключа нет ни в
-- коде, ни в БД: каталог прав кэшируется в памяти на 5 минут, и миграция «после» оставила бы
-- ключ видимым в «Ролях» до истечения кэша. Прежний бэкенд без этих строк работает штатно:
-- внешнего ключа на каталог у role_page_access нет, а сам ключ читала только вкладка-заглушка.
--
-- Если между этой миграцией и деплоем бэкенда кто-то сохранил роль из открытой заранее вкладки
-- «Роли», грант мог записаться снова — он ни на что не влияет и убирается повтором DELETE ниже.
-- Повторный запуск безопасен.

BEGIN;

DELETE FROM role_page_access WHERE page_path = '/salary/admin';
DELETE FROM access_pages     WHERE key       = '/salary/admin';

COMMIT;
