-- 340: «Справочник» → «Доплата» → «Разовая доплата»: основание выбирается из списка.
--
-- Зачем. Основание разовой доплаты вводили текстом, и одно и то же писали по-разному. Теперь в окне разовой
-- доплаты — выпадающий список, рядом ✎ открывает окно «Основания доплаты»: добавить, переименовать, удалить.
--
-- Основание у доплаты по-прежнему текст (payroll_one_time_supplements.reason, до 200 символов), без FK на список:
-- импорт разовых из 1С пишет вид 1С текстом, старые основания вне списка остаются как есть. Переименование в списке
-- меняет и основание у доплат с прежним названием; удаление убирает только строку списка.
--
-- Стартовый список — виды 1С из доп. начислений сентября 2026 и «Квартира», плюс уже внесённые основания (с теми же
-- правилами, что у сервера: пробелы схлопнуты, края обрезаны; длиннее 100 символов в список не попадают).
-- Автора не храним — добавление, переименование и удаление пишутся в аудит.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА. Прежний бэкенд с ней работает. Повторный запуск безопасен.

BEGIN;

CREATE TABLE IF NOT EXISTS payroll_supplement_reasons (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT payroll_supplement_reason_name CHECK (btrim(name) <> '' AND length(name) <= 100)
);

-- Без учёта регистра и пробелов по краям: «Премия» и « премия» — одно основание.
CREATE UNIQUE INDEX IF NOT EXISTS payroll_supplement_reasons_name_uniq
  ON payroll_supplement_reasons (lower(btrim(name)));

INSERT INTO payroll_supplement_reasons (name)
SELECT name
  FROM (
    VALUES ('Выходное пособие при увольнении'),
           ('Доплата'),
           ('Допработы'),
           ('Замещение'),
           ('Зарплата'),
           ('Квартира'),
           ('Компенсация использования личного а/м'),
           ('Матпомощь'),
           ('Перерасход п/о средств'),
           ('Перерасчет з/пл'),
           ('Премия'),
           ('Проезд'),
           ('Резерв')
  ) AS seed(name)
ON CONFLICT DO NOTHING;

-- Уже внесённые основания; несколько написаний одного (регистр) — берётся первое по алфавиту.
INSERT INTO payroll_supplement_reasons (name)
SELECT DISTINCT ON (lower(name)) name
  FROM (
    SELECT btrim(regexp_replace(reason, '\s+', ' ', 'g')) AS name FROM payroll_one_time_supplements
  ) used
 WHERE name <> '' AND length(name) <= 100
 ORDER BY lower(name), name
ON CONFLICT DO NOTHING;

COMMENT ON TABLE payroll_supplement_reasons IS
  'Список оснований разовой доплаты («Справочник» → «Доплата» → «Разовая доплата»). У доплаты основание — текст, не FK; переименование меняет и его. См. миграцию 340.';

REVOKE ALL ON TABLE public.payroll_supplement_reasons FROM PUBLIC;

COMMIT;
