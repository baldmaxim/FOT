-- 318: «Управление кадрами» — вкладка «Общежитие» переименована в «Проживание», новая вкладка «Удержания».
--
-- «Удержания»: кадры назначают сотруднику удержание (штраф) — вид, месяц удержания, сумма. Строка — одно
-- удержание; повторный штраф того же вида в том же месяце — новая строка (уникальности нет).
-- Виды — общий справочник с «Зарплатой» (payroll_deduction_kinds, миграция 299): вид, заведённый в кадрах,
-- виден в «Зарплате» → «Справочник» → «Удержания», и наоборот. У вида появляется сумма по умолчанию —
-- её подставляет окно добавления удержания, сумму строки можно изменить.
-- Вид, назначенный в кадрах, не удалить — FK RESTRICT (как отмеченный в «Зарплате»).
--
-- Автора не храним (без FK на пользователя) — добавление, правка и удаление пишутся в аудит.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА. Прежний бэкенд с ней работает. Повторный запуск безопасен.

BEGIN;

-- Вкладка «Общежитие» → «Проживание» (там будут общежитие и компенсация за квартиру). Ключ прежний.
UPDATE access_pages
   SET label = 'Управление кадрами — Проживание'
 WHERE key = '/staff-control/dormitory';

ALTER TABLE payroll_deduction_kinds ADD COLUMN IF NOT EXISTS default_amount NUMERIC(12,2);
ALTER TABLE payroll_deduction_kinds DROP CONSTRAINT IF EXISTS payroll_deduction_kind_default_amount;
ALTER TABLE payroll_deduction_kinds ADD CONSTRAINT payroll_deduction_kind_default_amount
  CHECK (default_amount IS NULL OR default_amount > 0);

COMMENT ON COLUMN payroll_deduction_kinds.default_amount IS
  'Сумма по умолчанию для удержания этого вида во вкладке «Управление кадрами» → «Удержания»; NULL — не задана. См. миграцию 318.';

CREATE TABLE IF NOT EXISTS staff_deductions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  kind_id     INTEGER NOT NULL REFERENCES payroll_deduction_kinds(id) ON DELETE RESTRICT,
  month       DATE NOT NULL,
  amount      NUMERIC(12,2) NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT staff_deduction_month CHECK (month = date_trunc('month', month)::date),
  CONSTRAINT staff_deduction_amount CHECK (amount > 0)
);

CREATE INDEX IF NOT EXISTS staff_deductions_employee_month ON staff_deductions (employee_id, month);
CREATE INDEX IF NOT EXISTS staff_deductions_kind ON staff_deductions (kind_id);

COMMENT ON TABLE staff_deductions IS
  'Удержания сотрудников («Управление кадрами» → «Удержания»): вид из payroll_deduction_kinds, месяц удержания (1-е число), сумма. См. миграцию 318.';

REVOKE ALL ON TABLE public.staff_deductions FROM PUBLIC;

-- Право «Управление кадрами — Удержания» (образец — 314).
INSERT INTO access_pages (
  key, label, group_code, group_label, area, surface,
  supports_edit, requires_data_scope, requires_employee_variant,
  sort_order, is_active, is_system
)
VALUES
  ('/staff-control/deductions', 'Управление кадрами — Удержания', 'work', 'Управление',
   'admin', 'technical', true, false, false, 109, true, true)
ON CONFLICT (key) DO UPDATE SET
  label         = EXCLUDED.label,
  group_code    = EXCLUDED.group_code,
  group_label   = EXCLUDED.group_label,
  area          = EXCLUDED.area,
  surface       = EXCLUDED.surface,
  supports_edit = EXCLUDED.supports_edit,
  sort_order    = EXCLUDED.sort_order,
  is_active     = EXCLUDED.is_active;

-- Сразу — администратор и кадровый админ; остальным — галочкой в «Ролях».
INSERT INTO role_page_access (role_code, page_path, can_view, can_edit)
VALUES
  ('admin',    '/staff-control/deductions', true, true),
  ('hr_admin', '/staff-control/deductions', true, true)
ON CONFLICT (role_code, page_path) DO UPDATE SET
  can_view = EXCLUDED.can_view,
  can_edit = EXCLUDED.can_edit;

COMMIT;
