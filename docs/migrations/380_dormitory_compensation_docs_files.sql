-- 380: «Проживание» → «Компенсация аренды»: «Обновление документов», справочное «Начало компенсации», файлы сотрудника.
--
-- Зачем (решения пользователя 25–26.11.2026, после пропажи Киличова Ш. Р. из списка ноября):
--   docs_updated_on — «Обновление документов»: дату вносят кадры (✎, «Добавить сотрудника»). Прежний столбец
--                     «Обновлено» показывал updated_at — время любой правки записи, а не документов; у текущих
--                     записей дата пустая. Дата не раньше паузы снимает её: компенсация возобновляется с этой даты.
--   since_on        — «Начало компенсации», как в 1С (2018, 2023…), если оно раньше начала расчёта: справочно, в
--                     расчёте не участвует. Расчёт — по check_in: прошлые (закрытые) месяцы кадры не меняют, начало
--                     новой компенсации не раньше открытого месяца (dormitory-compensation-dates.ts).
--   dormitory_compensation_files — файлы компенсации сотрудника (договор аренды, документы) в R2, как файлы шаблонов
--                     графиков (376): у сотрудника, а не у записи — не теряются при паузе и возобновлении. В общую
--                     таблицу documents не кладём: там файл увидел бы сотрудник в «Моих документах». Автора не храним:
--                     прикрепление и удаление пишутся в аудит (DORMITORY_COMPENSATION_FILE_UPLOADED / _DELETED).
--
-- Деньги: 0 изменений — новые колонки у существующих записей NULL, таблица пустая.
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА (deploy-server.sh migrate, затем backend): бэкенд пишет колонки и считает файлы
-- компенсации в списке месяца. Повторный запуск безопасен. Откат — docs/rollbacks/380_*.
-- Номер 380: 379 — 379_payroll_1c_payouts_api.sql.

BEGIN;

ALTER TABLE employee_dormitory_stays ADD COLUMN IF NOT EXISTS docs_updated_on DATE;
ALTER TABLE employee_dormitory_stays ADD COLUMN IF NOT EXISTS since_on DATE;

COMMENT ON COLUMN employee_dormitory_stays.docs_updated_on IS
  '«Обновление документов» компенсации аренды (миграция 380); только у вида apartment.';
COMMENT ON COLUMN employee_dormitory_stays.since_on IS
  'Справочное «Начало компенсации» раньше начала расчёта check_in (миграция 380); в расчёте не участвует.';

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'employee_dormitory_stay_docs_updated') THEN
    ALTER TABLE employee_dormitory_stays ADD CONSTRAINT employee_dormitory_stay_docs_updated
      CHECK (docs_updated_on IS NULL OR kind = 'apartment');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'employee_dormitory_stay_since') THEN
    ALTER TABLE employee_dormitory_stays ADD CONSTRAINT employee_dormitory_stay_since
      CHECK (since_on IS NULL OR (kind = 'apartment' AND since_on < check_in));
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS dormitory_compensation_files (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  r2_key      TEXT NOT NULL UNIQUE,
  file_name   TEXT NOT NULL,
  file_size   INTEGER NOT NULL,
  mime_type   TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT dormitory_compensation_file_r2_key CHECK (btrim(r2_key) <> ''),
  CONSTRAINT dormitory_compensation_file_name CHECK (btrim(file_name) <> '' AND length(file_name) <= 200),
  CONSTRAINT dormitory_compensation_file_size CHECK (file_size > 0 AND file_size <= 25 * 1024 * 1024),
  CONSTRAINT dormitory_compensation_file_mime CHECK (btrim(mime_type) <> '')
);

CREATE INDEX IF NOT EXISTS dormitory_compensation_files_employee
  ON dormitory_compensation_files (employee_id, created_at, id);

COMMENT ON TABLE dormitory_compensation_files IS
  'Файлы компенсации аренды сотрудника (R2): не больше 20, до 25 МБ, PDF/JPG/PNG/WEBP/DOC/DOCX/XLS/XLSX. См. миграцию 380.';

REVOKE ALL ON TABLE public.dormitory_compensation_files FROM PUBLIC;

COMMIT;
