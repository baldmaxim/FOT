-- 306: Зарплата — справочник ставок («Расчёты» → «Справочник»).
--
-- Зачем. На «Расчётах» рядом с шестерёнкой открывается окно «Справочник»: виды удержаний
-- (payroll_deduction_kinds, миграция 299 — теперь их можно переименовать и удалить) и отдельный
-- список ставок: название и значение. Ставка только хранится: в окно сотрудника и в расчёты
-- не подставляется, с видами удержаний не связана.
--
-- Значение можно не задавать (NULL) — ставку заводят, значение назначают позже.
-- Автора не храним (без FK на пользователя) — добавление, правка и удаление пишутся в аудит.
--
-- payroll_deduction_kinds не меняется: занятый вид от удаления стережёт FK RESTRICT
-- из payroll_employee_deductions (миграция 300).
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА. Прежний бэкенд с ней работает. Повторный запуск безопасен.

BEGIN;

CREATE TABLE IF NOT EXISTS payroll_rates (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  amount     NUMERIC(12,2),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT payroll_rate_name CHECK (btrim(name) <> '' AND length(name) <= 100),
  CONSTRAINT payroll_rate_amount CHECK (amount IS NULL OR amount >= 0)
);

-- Без учёта регистра и пробелов по краям: «Сварщик» и « сварщик» — одна ставка.
CREATE UNIQUE INDEX IF NOT EXISTS payroll_rates_name_uniq
  ON payroll_rates (lower(btrim(name)));

COMMENT ON TABLE payroll_rates IS
  'Справочник ставок («Зарплата → Расчёты» → «Справочник»): название и значение. Только хранится.';

REVOKE ALL ON TABLE public.payroll_rates FROM PUBLIC;

COMMIT;
