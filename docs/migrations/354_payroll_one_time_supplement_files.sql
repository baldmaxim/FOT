-- 354: файлы разовых доплат («Справочник» → «Доплата» → «Разовая доплата»): приказ, служебка, чек.
--
-- Строка — файл в R2 (r2_key). Удалили доплату — строки уходят каскадом, объекты R2 удаляет бэкенд
-- после коммита (best-effort). Видят файлы те же, кто видит «Доплату» (список доступа к «Зарплате», 310).
-- В общую таблицу documents не кладём: там файл увидел бы сотрудник в «Моих документах».
--
-- Автора не храним (без FK на пользователя, как у самих доплат в 315): прикрепление и снятие пишутся в
-- аудит в той же транзакции, что и строка файла.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА. Прежний бэкенд таблицу не читает. Повторный запуск безопасен.

BEGIN;

CREATE TABLE IF NOT EXISTS payroll_one_time_supplement_files (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplement_id INTEGER NOT NULL REFERENCES payroll_one_time_supplements(id) ON DELETE CASCADE,
  r2_key        TEXT NOT NULL UNIQUE,
  file_name     TEXT NOT NULL,
  file_size     INTEGER NOT NULL,
  mime_type     TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT payroll_one_time_supplement_file_name CHECK (btrim(file_name) <> '' AND length(file_name) <= 200),
  CONSTRAINT payroll_one_time_supplement_file_size CHECK (file_size > 0 AND file_size <= 25 * 1024 * 1024),
  CONSTRAINT payroll_one_time_supplement_file_mime CHECK (btrim(mime_type) <> '')
);

CREATE INDEX IF NOT EXISTS payroll_one_time_supplement_files_supplement
  ON payroll_one_time_supplement_files (supplement_id);

COMMENT ON TABLE payroll_one_time_supplement_files IS
  'Файлы разовых доплат (R2): не больше 10 у доплаты, до 25 МБ, PDF/JPG/PNG/WEBP/DOC/DOCX. См. миграцию 354.';

REVOKE ALL ON TABLE public.payroll_one_time_supplement_files FROM PUBLIC;

COMMIT;
