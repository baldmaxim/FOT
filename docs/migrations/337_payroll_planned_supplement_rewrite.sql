-- 337: Плановая доплата — правка и снятие любого периода, а не только последней строки журнала.
--
-- Зачем. У сотрудника бывает несколько периодов плановой доплаты (Корж: 20 000 до 30.09.2026,
-- 30 000 с 01.10.2026 по 31.01.2027, 20 000 с 01.02.2027). Журнал 293 правит только последнюю
-- строку: средний период не поправить и не снять — дописыванием строк его не убрать (период
-- скрывает только более поздняя пересекающая строка или «снята» сразу за ним), а точечный
-- UPDATE/DELETE «оживил» бы старые версии, которые прятала именно эта строка.
--
-- Правка периода переписывает расписание сотрудника: все его строки помечаются archived_at,
-- действующие периоды вставляются заново (правленый — с новыми значениями). Архивные строки
-- не участвуют ни в периодах, ни в «последней» строке — остаются только для истории.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА: новый бэкенд читает archived_at. Прежний бэкенд колонки не знает,
-- но и не пишет архивных строк — с ним миграция безопасна. Повторный запуск безопасен.

BEGIN;

ALTER TABLE payroll_planned_supplements
  ADD COLUMN IF NOT EXISTS archived_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS replaces_id BIGINT REFERENCES payroll_planned_supplements(id) ON DELETE SET NULL;

COMMENT ON COLUMN payroll_planned_supplements.archived_at IS
  'Строка заменена переписыванием расписания (правка или снятие периода): в периодах и «последней» строке '
  'не участвует, только история. NULL — действующая строка журнала.';
COMMENT ON COLUMN payroll_planned_supplements.replaces_id IS
  'Строка, которую заменила эта при переписывании расписания: «было» в истории. Копия без изменений '
  'в историю не попадает; строка «снята» (amount NULL) — снятый период.';

COMMIT;
