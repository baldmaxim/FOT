-- 361: «Должность» держателя подрядного пропуска вместо «КиГ действует до» + номер КиГ только латиницей.
--
-- Зачем. В окне «Документы» (Подрядчики → Мониторинг) поле «КиГ действует до» заменено на «Должность»:
-- она нужна листу «Биометрия» выгрузки «Экспорт в Excel». Должность — свободный текст, необязательна,
-- у всех граждан (не только у иностранцев). Те же колонки — в истории изменений документов (миграция 238).
-- kig_end_date НЕ удаляем: до деплоя бэкенда её пишет старый бэк; новый её не читает и не показывает.
--
-- Номер КиГ — только латинские буквы и цифры (так требует файл «Биометрия»). На проде 7 из 10 номеров
-- набраны кириллицей («АА…», «АВ…»), один с пробелом: кириллицу-двойники меняем на латиницу, пробелы
-- убираем. Это нормализация записи, а не правка документов, поэтому без снимка в историю и без updated_at.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА: новый бэкенд читает и пишет position. Повторный запуск безопасен.

BEGIN;
SET LOCAL lock_timeout = '5s';

ALTER TABLE public.contractor_passes
  ADD COLUMN IF NOT EXISTS position text;

ALTER TABLE public.contractor_pass_document_history
  ADD COLUMN IF NOT EXISTS position text;

UPDATE public.contractor_passes
   SET kig = NULLIF(
         translate(upper(regexp_replace(kig, '\s', '', 'g')),
                   'АВЕКМНОРСТУХ', 'ABEKMHOPCTYX'),
         '')
 WHERE kig IS NOT NULL
   AND kig !~ '^[A-Z0-9]+$';

COMMIT;
