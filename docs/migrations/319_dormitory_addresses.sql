-- 319: «Проживание» — сохранённые адреса общежитий для подсказок поля «Адрес / номер».
--
-- Подсказки = 9 общежитий компании (константа во фронтенде, не удаляются) + адреса из этой таблицы.
-- Адрес попадает сюда при первом сохранении проживания с ним и остаётся навсегда, даже если все записи
-- с ним удалят или исправят (раньше подсказки строились по текущим проживаниям, и адрес пропадал вместе
-- с последней записью). Удаления в интерфейсе нет — опечатку убирают запросом.
-- Один адрес без учёта регистра и пробелов по краям: «Общ1» и « общ1» — одна строка, остаётся первое написание.
--
-- Автора не храним (без FK на пользователя).
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА. Прежний бэкенд с ней работает. Повторный запуск безопасен.

BEGIN;

CREATE TABLE IF NOT EXISTS dormitory_addresses (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  address    TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT dormitory_address_text CHECK (btrim(address) <> '' AND length(address) <= 200)
);

CREATE UNIQUE INDEX IF NOT EXISTS dormitory_addresses_uniq ON dormitory_addresses (lower(btrim(address)));

COMMENT ON TABLE dormitory_addresses IS
  'Сохранённые адреса общежитий («Управление кадрами» → «Проживание»): подсказки поля «Адрес / номер», не удаляются вместе с проживаниями. См. миграцию 319.';

REVOKE ALL ON TABLE public.dormitory_addresses FROM PUBLIC;

-- Адреса уже сохранённых проживаний; из одинаковых без учёта регистра — написание самой ранней записи.
INSERT INTO dormitory_addresses (address)
SELECT DISTINCT ON (lower(btrim(address))) btrim(address)
  FROM employee_dormitory_stays
 ORDER BY lower(btrim(address)), id
ON CONFLICT DO NOTHING;

COMMIT;
