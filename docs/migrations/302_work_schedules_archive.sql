-- 302: Графики работы — архив шаблонов вместо удаления.
--
-- Зачем. Удаление шаблона каскадом стирало назначения (FK ON DELETE CASCADE), и прошлые дни
-- сотрудника, в том числе уволенного, пересчитывались по графику по умолчанию. Теперь «Удалить»
-- отправляет шаблон в архив: он скрыт из таблицы шаблонов и списков выбора, назначения и часы
-- остаются. В архив нельзя, пока график действует сейчас или с будущей даты у работающего
-- сотрудника или объекта.
--
-- ПРИМЕНЯТЬ ДО ДЕПЛОЯ БЭКЕНДА. Повторный запуск безопасен.

BEGIN;

ALTER TABLE public.work_schedules
  ADD COLUMN IF NOT EXISTS archived_at TIMESTAMPTZ;

COMMENT ON COLUMN public.work_schedules.archived_at IS
  'Когда шаблон отправлен в архив; NULL — действующий. Архивный не назначается, но резолвится в истории.';

COMMIT;
