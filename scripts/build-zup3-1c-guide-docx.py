def shade(element, color: str) -> None:
    props = element.get_or_add_pPr() if hasattr(element, 'get_or_add_pPr') else element.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), color)
    props.append(shd)


def add_runs(par, text: str) -> None:
    """Текст с **жирным** и `кодом`."""
    parts: list[tuple[str, str]] = []
    buf, mode, i = '', 'plain', 0
    while i < len(text):
        if text.startswith('**', i):
            parts.append((mode, buf)); buf = ''
            mode = 'plain' if mode == 'bold' else 'bold'
            i += 2
            continue
        if text[i] == '`':
            parts.append((mode, buf)); buf = ''
            mode = 'plain' if mode == 'code' else 'code'
            i += 1
            continue
        buf += text[i]
        i += 1
    parts.append((mode, buf))
    for kind, chunk in parts:
        if not chunk:
            continue
        run = par.add_run(chunk)
        if kind == 'bold':
            run.bold = True
        elif kind == 'code':
            run.font.name = 'Consolas'
            run.font.size = Pt(10)
            run.font.color.rgb = RGBColor(0x8B, 0x1A, 0x1A)


def h(level: int, text: str) -> None:
    doc.add_heading(text.replace('`', ''), level=level)


def p(text: str) -> None:
    add_runs(doc.add_paragraph(), text)


def bullets(items: list[str], style: str = 'List Bullet') -> None:
    for item in items:
        add_runs(doc.add_paragraph(style=style), item)


def steps(items: list[str]) -> None:
    """Нумерация с 1 в каждом списке (List Number в python-docx сквозной)."""
    for number, item in enumerate(items, start=1):
        par = doc.add_paragraph()
        par.paragraph_format.left_indent = Cm(0.9)
        par.paragraph_format.first_line_indent = Cm(-0.6)
        add_runs(par, f'{number}. {item}')


def note(text: str) -> None:
    par = doc.add_paragraph()
    shade(par._p, 'FFF4CE')
    par.paragraph_format.left_indent = Cm(0.3)
    add_runs(par, text)


def code(text: str) -> None:
    for line in text.strip('\n').split('\n'):
        par = doc.add_paragraph()
        par.paragraph_format.space_after = Pt(0)
        par.paragraph_format.line_spacing = 1.0
        shade(par._p, 'F2F2F2')
        run = par.add_run(line if line else ' ')
        run.font.name = 'Consolas'
        run.font.size = Pt(9)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def table(header: list[str], rows: list[list[str]], widths: list[float] | None = None) -> None:
    tbl = doc.add_table(rows=1, cols=len(header))
    tbl.style = 'Table Grid'
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    for idx, title in enumerate(header):
        cell = tbl.rows[0].cells[idx]
        cell.text = ''
        run = cell.paragraphs[0].add_run(title.replace('`', ''))
        run.bold = True
        shade(cell._tc, 'D9E2F3')
    for row in rows:
        cells = tbl.add_row().cells
        for idx, value in enumerate(row):
            cells[idx].text = ''
            add_runs(cells[idx].paragraphs[0], value)
    if widths:
        tbl.autofit = False
        for idx, width in enumerate(widths):
            tbl.columns[idx].width = Cm(width)
    for row in tbl.rows:
        for idx, cell in enumerate(row.cells):
            for par in cell.paragraphs:
                par.paragraph_format.space_after = Pt(0)
                for run in par.runs:
                    run.font.size = Pt(10)
            if widths:
                cell.width = Cm(widths[idx])
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


